"""Обновляет лендинг под допущения о данных (шкала 1-10 у обеих сторон, названия колонок, пара по ID).
Запуск из папки prototype после build_mock.py: python mgts/patch_site.py
Меняет site/index.html и publish/docs/index.html: заменяет раздел «Какие данные мы получаем», пример-график и тепловую карту.
Повторный запуск безопасен: раздел заменяется целиком, остальное правится регулярными выражениями."""
import json
import re
import sys
from html import escape as e
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
d = json.loads((Path(__file__).parent / "site_data.json").read_text(encoding="utf-8"))
P = {x["id"]: x for x in d["people"]}


def table(side, n=3):
    s = d["sample"][side]
    head = "".join(f"<th>{e(h)}</th>" for h in s["head"])
    rows = "".join("<tr>" + "".join(f"<td>{'' if v is None else e(str(v))}</td>" for v in r) + "</tr>" for r in s["rows"][:n])
    return f'<div class="dtw"><table class="dt"><tr>{head}</tr>{rows}</table></div>'


def li(t):
    return f"<li>{t}</li>"


SECTION = f"""<section id="data" class="card" aria-labelledby="dath">
      <h2 id="dath">Какие данные мы получаем<span class="tag">Допущения до финала</span></h2>
      <p class="sub">Формат описали на вебинаре 13 ноября. Точные названия колонок, шкалу и формулировки вопросов выдадут только на финале. Всё, что не названо, мы предположили (справа) и заложили в пример и в макет. На финале сверим с выданными файлами и поправим один файл настроек.</p>
      <div class="two">
        <div><h3>Что известно от организаторов</h3><ul>
          {li("Две таблицы Excel (упоминали и Word): ответы стажёров и ответы наставников за один период.")}
          {li("5 стажёров, 5 наставников, 6 ежемесячных опросов. Один наставник на одного стажёра.")}
          {li("Данные придуманные. У каждого стажёра и наставника свой уникальный ID, анкеты анонимные.")}
          {li("Стажёра спрашивают, как проходит стажировка и интересны ли задачи. Наставника спрашивают, как стажёр справляется, насколько оперативно и самостоятельно.")}
          {li("Вопросы не меняются между месяцами.")}
          {li("Нужно повторить анкету в Google Формах или похожем сервисе, чтобы ответы попадали в сервис, и сделать место, куда загружаются новые данные.")}
        </ul></div>
        <div><h3>Что мы предположили</h3><ul>
          {li("<b>Шкала:</b> от 1 до 10 у обеих сторон, максимум 10. Пустая ячейка означает «ответа нет», ноль не ставится.")}
          {li("<b>Колонки:</b> «ID стажёра» или «ID наставника», «Дата ответа» (ГГГГ-ММ-ДД), по одной колонке на каждый вопрос с оценкой, колонка с комментарием.")}
          {li("<b>Вопросы стажёра (4):</b> интересны ли задачи, понятны ли задачи, хватает ли поддержки наставника, хватает ли доступов и инструментов.")}
          {li("<b>Вопросы наставника (3):</b> как стажёр справляется с задачами, насколько оперативно, насколько самостоятельно.")}
          {li("<b>Пара:</b> стажёр С-03 и наставник Н-03 имеют одно число в ID. Если в данных есть колонка с парой, берём её.")}
          {li("<b>Месяц:</b> один ответ на человека в месяц, месяц берётся из даты. Период: июнь–ноябрь 2026.")}
          {li("<b>Комментарии:</b> есть у обеих сторон, необязательные.")}
        </ul></div>
      </div>
      <h3 style="font:700 15px var(--font-head);margin:6px 0 0">Так выглядят две таблицы в нашем примере</h3>
      <p class="note" style="margin:4px 0 0">Таблица 1. Ответы стажёров (шкала 1–10)</p>{table("i")}
      <p class="note" style="margin:0">Таблица 2. Ответы наставников (шкала 1–10)</p>{table("m")}
      <ul class="points">
        <li><span class="dot"><svg viewBox="0 0 24 24"><path d="M4 8h16M4 16h16M9 4l-4 4 4 4M15 12l4 4-4 4"/></svg></span><div><b>Пара по ID</b><span>Если колонки с парой нет, наставник Н-03 сопоставляется стажёру С-03 по числу в ID. Такие пары программа выводит в отчёт на проверку.</span></div></li>
        <li><span class="dot"><svg viewBox="0 0 24 24"><path d="M3 20h18M6 16l4-5 3 3 5-8"/></svg></span><div><b>Если шкалы окажутся другими</b><span>Шкалы 1–5, 1–7 и любые другие приводятся к 1–10. Исходные значения остаются в базе.</span></div></li>
        <li><span class="dot"><svg viewBox="0 0 24 24"><path d="M12 3v12M7 10l5 5 5-5M4 20h16"/></svg></span><div><b>Пропуск остаётся пропуском</b><span>Пустая ячейка не превращается в ноль. Повторная загрузка файла не создаёт дублей.</span></div></li>
        <li><span class="dot"><svg viewBox="0 0 24 24"><path d="M5 12l4 4 10-10"/></svg></span><div><b>Разные вопросы у сторон</b><span>Вопросы стажёра и наставника сравниваются по парам, которые мы задаём в одном файле. Вопросы без пары показываются отдельно.</span></div></li>
      </ul>
      <p class="note">Готовые шаблоны двух таблиц и файл сопоставления колонок лежат в папке <code>prototype/mgts</code>. На финале мы смотрим выданные файлы командой <code>inspect_data.py</code>, правим названия колонок и шкалу и загружаем данные. По плану это занимает 30–40 минут.</p>
    </section>

    """

I4 = P["С-04"]["i"]["clarity"]
T4 = P["С-04"]["m"]["performance"]
HEAT = json.dumps([[x["mentor"], x["m"]["performance"]] for x in d["people"]], ensure_ascii=False)
EXAMPLE_SUB = "стажёр отвечает на «Насколько понятны задачи», наставник на «Как стажёр справляется с задачами». Шкала 1–10 у обеих сторон."
EXAMPLE_NOTE = "С сентября наставник снижает оценку с 9 до 4, а стажёр по-прежнему ставит 8 и считает задачи понятными. Стороны видят ситуацию по-разному: это расхождение попадает в список для проверки."
LEGEND = ('<div class="hl"><span><i style="background:var(--g-bg);border:1px solid var(--g-bd)"></i>хорошо: 8–10 из 10</span>'
          '<span><i style="background:var(--m-bg);border:1px solid var(--m-bd)"></i>средне: 6–7</span>'
          '<span><i style="background:var(--r-bg);border:1px solid var(--r-bd)"></i>плохо: 5 и ниже</span></div>')

# (шаблон, замена, регулярное?): замены регулярными выражениями делаются через функцию, поэтому спецсимволы в тексте безопасны
R = [
    (r'<section id="data".*?</section>\s*', SECTION, True),
    ("<p>Пять экранов на выдуманных данных в формате вебинара.</p>", "<p>Три экрана на выдуманных данных в формате вебинара.</p>", False),
    (r"I=\[[^\]]*\],T=\[[^\]]*\];", f"I={I4},T={T4};", True),
    ("Стажёр 4 из 5 · Наставник 4 из 10", "Стажёр 8 · Наставник 4", False),
    ('<rect width="214" height="50"', '<rect width="150" height="50"', False),
    ("translate('+(x(5)-226)+'", "translate('+(x(5)-162)+'", False),
    (r"(Выдуманные данные из макета\. Вопросы у сторон разные, поэтому сравниваем пару: )[^<]*", None, True),
    (r'aria-label="Оценка наставника «Справляется с задачами» снижается[^"]*"', 'aria-label="Оценка наставника «Справляется с задачами» снижается с 9 до 4, оценка стажёра «Понятные задачи» остаётся 8"', True),
    (r"С сентября наставник снижает[^<]*", EXAMPLE_NOTE, True),
    ("var k=v/10>=.7?' good':v/10>.5?' mid':' low';", "var k=v>=8?' good':v>=6?' mid':' low';", False),
    (r'<div class="hl">.*?</div>', LEGEND, True),
    (r"var P=\[\[.*?\]\]\];", "var P=" + HEAT + ";", True),
]
for path in [ROOT / "site/index.html", ROOT / "publish/docs/index.html"] + [Path(a) for a in sys.argv[1:]]:
    s = path.read_text(encoding="utf-8")
    for old, new, rx in R:
        if rx:
            fn = (lambda m: m.group(1) + EXAMPLE_SUB) if new is None else (lambda m, new=new: new)
            s, n = re.subn(old, fn, s, count=1, flags=re.S)
            if n != 1:
                raise SystemExit(f"не найдено: {old[:60]}")
        else:
            if old not in s and new not in s:
                raise SystemExit(f"не найдено: {old[:60]}")
            s = s.replace(old, new, 1)
    path.write_text(s, encoding="utf-8", newline="")
    print("ок:", path)
